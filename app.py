def _demo_reply(prompt: str) -> str:
    """Transparent offline preview; no language model is called in demo mode."""
    lowered = prompt.lower()
    dataset_path = BASE_DIR / "sample_data" / "project_metrics.csv"
    if any(word in lowered for word in ("csv", "dataset", "metrics", "progress", "analyse", "analyze", "data")):
        try:
            data = pd.read_csv(dataset_path)
            avg_progress = data["completion_percent"].mean()
            delayed = int((data["status"].str.lower() == "delayed").sum())
            critical = int((data["risk_level"].str.lower() == "high").sum())
            return (
                "**Offline demo analysis (sample data only)**\n\n"
                f"- Work items in the sample dataset: **{len(data)}**\n"
                f"- Average completion: **{avg_progress:.1f}%**\n"
                f"- Items marked delayed: **{delayed}**\n"
                f"- Items marked high risk: **{critical}**\n\n"
                "In the live Foundry configuration, the agent's Code Interpreter should be used "
                "for richer analysis and any chart generation. These are synthetic example metrics, "
                "not your college's actual project data."
            )
        except Exception:
            pass
    if any(word in lowered for word in ("plan", "project", "build", "idea", "roadmap")):
        return (
            "**Offline demo response — not generated by Microsoft Foundry**\n\n"
            "A useful first project plan should define:\n\n"
            "1. **Problem and users:** who has the problem and how you know it exists.\n"
            "2. **Minimum viable product:** three core features, not a long wishlist.\n"
            "3. **Architecture:** user interface, API/service layer, data sources, and AI agent.\n"
            "4. **Milestones:** requirements, prototype, integration, testing, and demonstration.\n"
            "5. **Evaluation:** a small test set, expected outcomes, failures, latency, and estimated cost.\n\n"
            "Connect the Foundry agent to replace this preview with a real agent response."
        )
    return (
        "ProjectPilot AI helps turn project ideas into scoped plans and data questions into "
        "testable analysis. This is an offline UI preview. Set `DEMO_MODE=false`, configure the "
        "Foundry endpoint and agent name in `.env`, and sign in with `az login` to call your real agent."
    )


@st.cache_resource(show_spinner=False)
def _foundry_clients(endpoint: str):
    """Create reusable Microsoft Foundry clients using Azure CLI / Entra auth."""
    from azure.ai.projects import AIProjectClient
    from azure.identity import DefaultAzureCredential

    credential = DefaultAzureCredential()
    project_client = AIProjectClient(endpoint=endpoint, credential=credential)
    openai_client = project_client.get_openai_client()
    return project_client, openai_client


def ask_foundry(prompt: str) -> str:
    if not FOUNDRY_PROJECT_ENDPOINT:
        raise RuntimeError("FOUNDRY_PROJECT_ENDPOINT is missing from .env")
    if not FOUNDRY_AGENT_NAME:
        raise RuntimeError("FOUNDRY_AGENT_NAME is missing from .env")

    _, openai_client = _foundry_clients(FOUNDRY_PROJECT_ENDPOINT)
    if not st.session_state.get("conversation_id"):
        conversation = openai_client.conversations.create()
        st.session_state.conversation_id = conversation.id

    # This follows the agent_reference pattern used in the supplied Microsoft
    # Learning agent lab. The named agent and its tools must already exist.
    response = openai_client.responses.create(
        conversation=st.session_state.conversation_id,
        input=prompt,
        extra_body={
            "agent_reference": {
                "name": FOUNDRY_AGENT_NAME,
                "type": "agent_reference",
            }
        },
    )
    output = getattr(response, "output_text", "")
    if output:
        return output
    return "The agent returned no text output. Inspect the Foundry run trace for details."


