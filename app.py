# --- CSV chart generation and download ---
st.divider()
st.markdown("### Create and download a memory-usage chart")

uploaded_chart_csv = st.file_uploader(
    "Upload system_performance.csv",
    type=["csv"],
    key="memory_chart_upload",
)

if uploaded_chart_csv is not None:
    try:
        chart_df = pd.read_csv(uploaded_chart_csv)

        time_col = next(
            (c for c in chart_df.columns
             if any(w in c.lower()
                    for w in ("timestamp", "datetime", "time", "date"))),
            None,
        )
        memory_col = next(
            (c for c in chart_df.columns
             if any(w in c.lower()
                    for w in ("memory", "mem", "ram"))),
            None,
        )

        if memory_col is None:
            st.error("Could not identify the memory-usage column.")
        else:
            memory = pd.to_numeric(
                chart_df[memory_col].astype(str)
                .str.replace("%", "", regex=False),
                errors="coerce",
            )

            if time_col:
                times = pd.to_datetime(
                    chart_df[time_col], errors="coerce"
                )
                valid = memory.notna() & times.notna()
                plot_df = pd.DataFrame({
                    "time": times[valid],
                    "memory": memory[valid],
                }).sort_values("time")
                x = plot_df["time"]
                y = plot_df["memory"]
                x_label = time_col
            else:
                valid = memory.notna()
                x = chart_df.index[valid] + 1
                y = memory[valid]
                x_label = "Row number"

            if len(y) == 0:
                st.error("No usable numeric memory values were found.")
            else:
                fig, ax = plt.subplots(figsize=(10, 4))
                ax.plot(x, y, marker="o")
                ax.set_title("Memory Usage Over Time")
                ax.set_xlabel(x_label)
                ax.set_ylabel(f"{memory_col} (%)")
                ax.grid(True, alpha=0.3)
                fig.tight_layout()

                st.pyplot(fig)

                chart_bytes = io.BytesIO()
                fig.savefig(chart_bytes, format="png", dpi=160)
                plt.close(fig)

                st.download_button(
                    "Download memory chart (PNG)",
                    data=chart_bytes.getvalue(),
                    file_name="memory_usage_over_time.png",
                    mime="image/png",
                )

    except Exception as exc:
        st.error(f"Could not process the CSV: {exc}")